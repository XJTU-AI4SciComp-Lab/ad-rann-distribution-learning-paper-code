function [cfg,project_root] = config_diffusion_reaction_deeponet(mode)
%CONFIG_DIFFUSION_REACTION_DEEPONET Portable DeepONet experiment config.
%
% mode:
%   'RANN_DDAD'    - supervised RaNN-DeepONet + DDAD
%   'PI_RANN_DDAD' - PI-RaNN-DeepONet + at most two DDAD updates

    project_root = initialize_paths(mfilename('fullpath'));

    if nargin < 1 || isempty(mode)
        mode = 'RANN_DDAD';
    end

    mode = upper(strtrim(char(mode)));

    if ~ismember(mode,{'RANN_DDAD','PI_RANN_DDAD'})
        error('mode must be RANN_DDAD or PI_RANN_DDAD.');
    end

    cfg = struct();
    cfg.mode = mode;
    cfg.seed = 42;
    cfg.activation = 'tanh';
    cfg.verbose = true;

    % Data paths are resolved relative to project_root/data.
    cfg.data.training_file = 'Diffusion10000.mat';
    cfg.data.test_file = 'Diffusion_test1000.mat';

    % Training layout: 100 coordinates for each of 10,000 functions.
    % This is intentionally independent of the 100-by-100 test grid.
    cfg.data.points_per_function = 100;

    % Full model used for the final fit.
    cfg.model.num_sensors = 100;
    cfg.model.num_branch = 120;
    cfg.model.num_trunk = 100;
    cfg.model.num_training_rows = 40000;

    % Reduced model used only during DDAD scale adaptation.
    cfg.reduced.num_branch = 60;
    cfg.reduced.num_trunk = 50;
    cfg.reduced.num_training_rows = 20000;

    % Parameter order is always [rb;rx;rt].
    if strcmp(mode,'PI_RANN_DDAD')
        cfg.initial_p = [1;1;1];
    else
        cfg.initial_p = [1;1;1];
    end

    cfg.ddad.lambda = 1e-7;
    cfg.ddad.optimizer = base_optimizer();

    % Supervised final output-coefficient fit.
    cfg.data_fit.lambda = 0;

    % PDE: u_t-D*u_xx-k*u^2=f(x), with homogeneous initial/boundary data.
    cfg.physics.diffusion = 0.01;
    cfg.physics.reaction = 0.01;
    cfg.physics.lambda = 0;
    cfg.physics.max_picard_iterations = 3;
    cfg.physics.relaxation = 1;
    cfg.physics.relative_tolerance = 1e-8;

    % PI-RaNN uses DDAD targets generated by its current physical solution.
    cfg.physics.max_ddad_updates = 2;
    cfg.physics.ddad_update_tolerance = 1e-8;

    cfg.linear_solver.method = 'linsolve';
    cfg.linear_solver.use_gpu = gpu_is_available();
    cfg.linear_solver.gpu_id = 6;
    cfg.linear_solver.compute_spectrum = false;

    % The supplied test set contains 100-by-100 points per input function.
    cfg.test.grid_shape = [100,100];
    cfg.test.function_batch_size = 25;

    cfg.output_root_name = ...
        fullfile('results','diffusion_reaction_deeponet');
end


function opt = base_optimizer()
%BASE_OPTIMIZER Paper-aligned three-scale DDAD options.

    opt = struct();
    opt.maxit = 70;

    % Parameter order [rb;rx;rt]: branch 0.02, trunk 0.2.
    opt.learning_rate = 0.2*[1;1;1];

    opt.beta1 = 0.9;
    opt.beta2 = 0.999;
    opt.epsilon = 1e-8;

    opt.lower_bound = [1e-4;1e-4;1e-4];
    opt.upper_bound = [300;300;300];
    opt.parameterization = 'log';
    opt.selection_metric = 'residual_mse';

    opt.grad_tol = 1e-10;
    opt.step_tol = 1e-11;
    opt.relative_obj_tol = 1e-11;
    opt.patience = Inf;
    opt.min_delta = 0;

    opt.store_moments = true;
    opt.store_full_info = false;
    opt.verbose = true;
end


function available = gpu_is_available()

    available = false;

    if exist('canUseGPU','file') == 2
        try
            available = canUseGPU;
        catch
            available = false;
        end
    end
end


function project_root = initialize_paths(config_file)
%INITIALIZE_PATHS Locate the project root from this config file.

    persistent cached_project_root path_initialized

    if ~isempty(cached_project_root) && ...
       exist(cached_project_root,'dir') == 7

        project_root = cached_project_root;

        if isempty(path_initialized) || ~path_initialized
            addpath(genpath(fullfile(project_root,'src')));
            path_initialized = true;
        end

        return;
    end

    example_dir = fileparts(config_file);
    project_root = fileparts(fileparts(example_dir));

    required_dirs = { ...
        fullfile(project_root,'src'), ...
        fullfile(project_root,'data'), ...
        fullfile(project_root,'examples')};

    for k = 1:numel(required_dirs)
        if exist(required_dirs{k},'dir') ~= 7
            error('Required project directory not found: %s', ...
                required_dirs{k});
        end
    end

    addpath(genpath(fullfile(project_root,'src')));
    rehash path;

    required_functions = { ...
        'build_random_weights_nd', ...
        'build_preactivation', ...
        'activation_derivatives', ...
        'feature_derivatives_2d', ...
        'optimize_distribution_adam', ...
        'solve_ridge', ...
        'solve_least_squares', ...
        'diffusion_reaction_deeponet_study'};

    for k = 1:numel(required_functions)
        if isempty(which(required_functions{k}))
            error('Required project function not found: %s', ...
                required_functions{k});
        end
    end

    cached_project_root = project_root;
    path_initialized = true;

    fprintf('Project root: %s\n',project_root);
    fprintf('DeepONet example: %s\n',example_dir);
    fprintf('DeepONet implementation: %s\n', ...
        fullfile(project_root,'src','problem_dependent', ...
        'diffusion_reaction_deeponet'));
end
