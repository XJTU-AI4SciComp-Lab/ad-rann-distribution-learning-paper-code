function plot_poisson_lshape_result(results)
%PLOT_POISSON_LSHAPE_RESULT Exact, numerical, error and growth-center plots.
%
% The L-shaped domain is
%   (-1,1)^2 \ ([0,1] x [-1,0]),
% so the missing square is always displayed in the lower-right corner.

    cfg = results.cfg;
    E = results.evaluation;

    x = E.grid.x;
    y = E.grid.y;

    fig1 = figure( ...
        'Color','w', ...
        'Name',['Poisson L-shape ' cfg.method], ...
        'NumberTitle','off');

    tiledlayout(1,3, ...
        'Padding','compact', ...
        'TileSpacing','compact');

    nexttile;

    contourf( ...
        x, ...
        y, ...
        E.grid.U_exact, ...
        50, ...
        'LineColor','none');

    hold on;
    draw_lshape_boundary();
    hold off;

    axis equal tight;
    set(gca,'YDir','normal');
    box on;
    colorbar;

    xlabel('$x$', ...
        'Interpreter','latex', ...
        'FontSize',14);

    ylabel('$y$', ...
        'Interpreter','latex', ...
        'FontSize',14);

    title( ...
        'Exact singular solution', ...
        'FontSize',12);

    set(gca, ...
        'FontSize',12, ...
        'LineWidth',1);


    nexttile;

    contourf( ...
        x, ...
        y, ...
        E.grid.U_pred, ...
        50, ...
        'LineColor','none');

    hold on;
    draw_lshape_boundary();
    hold off;

    axis equal tight;
    set(gca,'YDir','normal');
    box on;
    colorbar;

    xlabel('$x$', ...
        'Interpreter','latex', ...
        'FontSize',14);

    ylabel('$y$', ...
        'Interpreter','latex', ...
        'FontSize',14);

    title( ...
        sprintf('%s approximation',strrep(cfg.method,'_','+')), ...
        'FontSize',12);

    set(gca, ...
        'FontSize',12, ...
        'LineWidth',1);


    nexttile;

    contourf( ...
        x, ...
        y, ...
        E.grid.U_error, ...
        50, ...
        'LineColor','none');

    hold on;
    draw_lshape_boundary();
    hold off;

    axis equal tight;
    set(gca,'YDir','normal');
    box on;
    colorbar;

    xlabel('$x$', ...
        'Interpreter','latex', ...
        'FontSize',14);

    ylabel('$y$', ...
        'Interpreter','latex', ...
        'FontSize',14);

    title( ...
        sprintf('Absolute error, rel. $L^2=%.2e$', ...
            E.relative_l2), ...
        'Interpreter','latex', ...
        'FontSize',12);

    set(gca, ...
        'FontSize',12, ...
        'LineWidth',1);

    colormap(parula);

    figure_file = fullfile( ...
        results.output_dir, ...
        sprintf( ...
            'poisson_lshape_2d_%s_fields.png', ...
            lower(cfg.method)));

    exportgraphics( ...
        fig1, ...
        figure_file, ...
        'Resolution',300);


    if cfg.growth.enabled

        fig2 = figure( ...
            'Color','w', ...
            'Name','L-shape growth centers', ...
            'NumberTitle','off');

        contourf( ...
            x, ...
            y, ...
            E.grid.U_error, ...
            40, ...
            'LineColor','none');

        hold on;

        draw_lshape_boundary();

        plot( ...
            results.growth_centers(:,1), ...
            results.growth_centers(:,2), ...
            'ko', ...
            'LineStyle','none', ...
            'MarkerSize',3.5, ...
            'LineWidth',0.6);

        hold off;

        axis equal tight;
        set(gca,'YDir','normal');
        box on;
        colorbar;

        xlabel('$x$', ...
            'Interpreter','latex', ...
            'FontSize',14);

        ylabel('$y$', ...
            'Interpreter','latex', ...
            'FontSize',14);

        title( ...
            'Residual-selected centers for layer growth', ...
            'FontSize',12);

        set(gca, ...
            'FontSize',12, ...
            'LineWidth',1);

        colormap(parula);

        center_file = fullfile( ...
            results.output_dir, ...
            'poisson_lshape_2d_growth_centers.png');

        exportgraphics( ...
            fig2, ...
            center_file, ...
            'Resolution',300);

    end

end


function draw_lshape_boundary()
%DRAW_LSHAPE_BOUNDARY Draw the boundary with a lower-right cut-out.

    xb = [ ...
        -1, ...
         1, ...
         1, ...
         0, ...
         0, ...
        -1, ...
        -1];

    yb = [ ...
         1, ...
         1, ...
         0, ...
         0, ...
        -1, ...
        -1, ...
         1];

    plot( ...
        xb, ...
        yb, ...
        'k-', ...
        'LineWidth',1.1);

end
